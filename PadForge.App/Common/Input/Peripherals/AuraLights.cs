using System;
using System.Collections.Generic;

namespace PadForge.Common.Input.Peripherals
{
    /// <summary>
    /// The ASUS Aura SDK's devices as PadForge's paths see them (#557): one
    /// path per kind of device, the way Chroma has one per category, since
    /// the SDK names a device by its type and its name alone, with no
    /// product ID or device path a row could be matched by
    /// (IAuraSyncDevice: Lights, Type, Name, Width, Height and Apply, read
    /// from Interop.AuraServiceLib.dll, the interop assembly RGB.NET,
    /// Aurora and Artemis carry, SHA-256 B82FC09C363FF94B...).
    ///
    /// <para>A path's lights. The keyboard path takes every key RGB.NET
    /// maps (<see cref="KeyboardKeys"/>, generated by
    /// tools/gen_aura_key_table.py from RGB.NET.Devices.Asus
    /// Keyboard/AsusKeyboardLedMapping.cs), addressed by the Aura key code,
    /// which IAuraSyncKeyboard.Key takes. A keyboard lit in zones
    /// (KEYBOARD_5ZONE_RGB, NB_KB_4ZONE_RGB) is lit through its Lights
    /// list, as RGB.NET lights it (AsusKeyboardRGBDevice.cs:410-415), so
    /// once the session has read the devices the path also carries one
    /// zone light per index of the longest such list, at
    /// <see cref="ZoneBase"/> plus the index. Every other path carries one
    /// zone per index of the longest Lights list among its devices, as
    /// RGB.NET lights each light of a mainboard, a graphics card or any
    /// other device as one LED (AsusMainboardRGBDevice.cs:575-580,
    /// AsusUnspecifiedRGBDevice.cs:307-312). Two devices of one path show
    /// the same colors at the same index.</para>
    /// </summary>
    internal static partial class AuraLights
    {
        /// <summary>The first zone light's address on the keyboard path,
        /// clear of every key code (the highest is 0x103).</summary>
        internal const int ZoneBase = 0x10000;

        /// <summary>The paths, in the order the worker paints them.</summary>
        internal static readonly string[] Categories =
            { "keyboard", "mouse", "headset", "mainboard", "strip", "vga", "dram", "other" };

        // AsusDeviceType (RGB.NET.Devices.Asus Enum/AsusDeviceType.cs:7-25).
        internal const uint MbRgb = 0x10000;
        internal const uint MbAddressable = 0x11000;
        internal const uint VgaRgb = 0x20000;
        internal const uint HeadsetRgb = 0x40000;
        internal const uint DramRgb = 0x70000;
        internal const uint KeyboardRgb = 0x80000;
        internal const uint Keyboard5ZoneRgb = 0x80001;
        internal const uint NotebookKeyboardRgb = 0x81000;
        internal const uint NotebookKeyboard4ZoneRgb = 0x81001;
        internal const uint MouseRgb = 0x90000;

        /// <summary>The path a device of an Aura type is lit through, by
        /// the device classes RGB.NET's provider gives each type
        /// (AsusDeviceProvider.cs:78-92). The types it lights as an
        /// unspecified device, and every type it does not name, go to the
        /// "other" path.</summary>
        internal static string CategoryOf(uint type) => type switch
        {
            KeyboardRgb or Keyboard5ZoneRgb or NotebookKeyboardRgb or NotebookKeyboard4ZoneRgb => "keyboard",
            MouseRgb => "mouse",
            HeadsetRgb => "headset",
            MbRgb => "mainboard",
            MbAddressable => "strip",
            VgaRgb => "vga",
            DramRgb => "dram",
            _ => "other",
        };

        /// <summary>Whether a type is lit key by key through
        /// IAuraSyncKeyboard.Key, as RGB.NET writes KEYBOARD_RGB and
        /// NB_KB_RGB (AsusUpdateQueue.cs:162-176). Every other type is lit
        /// through its Lights list (AsusUpdateQueue.cs:188-199).</summary>
        internal static bool PerKey(uint type) => type == KeyboardRgb || type == NotebookKeyboardRgb;

        private static readonly Lazy<LightMap> s_keyboard = new(() => BuildKeyboard(0));

        /// <summary>The keyboard path's lights before the session has read
        /// the devices: every key of <see cref="KeyboardKeys"/>.</summary>
        internal static LightMap KeyboardMap => s_keyboard.Value;

        /// <summary>The lights of a path, from the devices the session
        /// read, or null for a path that lights one color: no device, or
        /// devices with one light each and no keys.</summary>
        internal static LightMap MapFor(string category, IReadOnlyList<AuraDevice> devices)
        {
            int zones = 0;
            foreach (var device in devices ?? Array.Empty<AuraDevice>())
            {
                if (CategoryOf(device.Type) != category) continue;
                if (category == "keyboard" && PerKey(device.Type)) continue;
                zones = Math.Max(zones, device.LightCount);
            }
            if (category == "keyboard") return zones == 0 ? KeyboardMap : BuildKeyboard(zones);
            if (zones < 2) return null;
            var lights = new LightInfo[zones];
            for (int i = 0; i < zones; i++)
                lights[i] = new LightInfo(i, LightKind.Zone, 0, LightKeySource.None) { Zone = i + 1 };
            return new LightMap(lights, "ASUS Aura SDK, " + category + " lights");
        }

        private static LightMap BuildKeyboard(int zones)
        {
            var lights = new List<LightInfo>(KeyboardKeys.Length + zones);
            foreach (var key in KeyboardKeys)
                lights.Add(new LightInfo(key.Code, key.Kind, key.Usage, key.Usage != 0 ? LightKeySource.Vendor : LightKeySource.None)
                {
                    Label = key.Label,
                });
            for (int i = 0; i < zones; i++)
                lights.Add(new LightInfo(ZoneBase + i, LightKind.Zone, 0, LightKeySource.None) { Zone = i + 1 });
            lights.Sort((a, b) => a.Address.CompareTo(b.Address));
            return new LightMap(lights, "ASUS Aura SDK, RGB.NET.Devices.Asus LedMappings.KeyboardMapping");
        }
    }

    /// <summary>One device the Aura SDK reported: its index in the
    /// enumeration, its type and name, how many lights its Lights list
    /// holds, and for a keyboard lit key by key the codes of its keys
    /// (IAuraSyncKeyboard.Keys, IAuraRgbKey.Code).</summary>
    internal sealed record AuraDevice(int Index, uint Type, string Name, int LightCount, IReadOnlyList<ushort> KeyCodes);
}
