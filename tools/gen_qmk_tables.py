"""The QMK keyboard tables, from OpenRGB (#557).

WHAT IT READS, under OpenRGB's Controllers/QMKController:
- QMKKeycodes.h and QMKKeycodes.cpp: qmk_keynames, OpenRGB's name for each
  QMK keycode a key's LED reports. A std::map built from an initializer list
  keeps the first entry of a keycode listed twice, and so does this script.
- QMKKeychronController/QMKKeychronController_Devices.h and .cpp: the
  Keychron matrix patches, in the order of keychron_patches[], each a
  product ID and the cells it moves (source row and column to row and
  column). The controller applies the first patch whose product ID matches.
- RGBController/RGBControllerKeyNames.cpp: the string behind each KEY_ name.

WHAT IT WRITES. PadForge.App/Common/Input/Peripherals/HidFamilies/QmkTables.g.cs.

Run without Python's -I switch: it imports tools/openrgb_cpp.py.

Usage:
    python tools/gen_qmk_tables.py OPENRGB_ROOT
    python tools/gen_qmk_tables.py OPENRGB_ROOT --check   (compare, write nothing)
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import openrgb_cpp as cpp  # noqa: E402

PROJ_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(PROJ_ROOT, "PadForge.App", "Common", "Input", "Peripherals", "HidFamilies", "QmkTables.g.cs")

Q = "Controllers/QMKController/"
KEYCODES_H = Q + "QMKKeycodes.h"
KEYCODES_CPP = Q + "QMKKeycodes.cpp"
DEVICES_H = Q + "QMKKeychronController/QMKKeychronController_Devices.h"
DEVICES_CPP = Q + "QMKKeychronController/QMKKeychronController_Devices.cpp"
KEY_NAMES = "RGBController/RGBControllerKeyNames.cpp"


def cs_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def key_names(root):
    with open(os.path.join(root, KEY_NAMES), encoding="utf-8-sig") as f:
        text = f.read()
    names = {}
    for name, literal in re.findall(r'const\s+char\s*\*\s*(\w+)\s*=\s*("(?:[^"\\]|\\.)*")\s*;', text):
        names[name] = cpp.decode_string(literal)
    return names


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("openrgb")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.openrgb.replace("\\", "/")
    commit = cpp.git_head(root)

    kh = cpp.Source(root, KEYCODES_H)
    kc = cpp.Source(root, KEYCODES_CPP)
    ev = cpp.Evaluator([kh, kc], strings=key_names(root))
    cpp.add_enum_constants(ev, kh)
    node, names_line = kc.definition("qmk_keynames")
    keynames = []
    seen = set()
    for entry in node:
        if not isinstance(entry, cpp.Node) or len(entry) != 2:
            sys.exit("qmk_keynames: entry at line %d" % entry.line)
        code = ev.integer(entry[0])
        name = ev.string(entry[1])
        if code in seen:
            continue
        seen.add(code)
        keynames.append((code, name, entry.line))

    dh = cpp.Source(root, DEVICES_H)
    dc = cpp.Source(root, DEVICES_CPP)
    dev = cpp.Evaluator([dh, dc])
    entries = {}
    for name in dc.definitions_of_type("keychron_patch_entry"):
        body, line = dc.definition(name)
        cells = []
        for item in body:
            if not isinstance(item, cpp.Node) or len(item) != 4:
                sys.exit("%s: entry at line %d" % (name, item.line))
            cells.append(tuple(dev.integer(x) for x in item))
        entries[name] = (cells, line)
    patches = {}
    for name in dc.definitions_of_type("keychron_patch"):
        body, line = dc.definition(name)
        if len(body) != 3:
            sys.exit("%s: %d fields" % (name, len(body)))
        pid = dev.integer(body[0])
        source = body[2]
        if len(source) != 1 or source[0].text not in entries:
            sys.exit("%s: unknown entries %r" % (name, source))
        patches[name] = (pid, source[0].text, line)
    order_node, order_line = dc.definition("keychron_patches")
    order = []
    for item in order_node:
        toks = [t.text for t in item]
        if len(toks) != 2 or toks[0] != "&" or toks[1] not in patches:
            sys.exit("keychron_patches: %r" % toks)
        order.append(toks[1])

    out = []
    out.append("// <auto-generated>")
    out.append("//     Generated by tools/gen_qmk_tables.py from OpenRGB at %s" % commit[:10])
    out.append("//     (Controllers/QMKController: qmk_keynames of QMKKeycodes.cpp with the")
    out.append("//     keycodes of QMKKeycodes.h, and the Keychron matrix patches of")
    out.append("//     QMKKeychronController_Devices.cpp, with the key names of")
    out.append("//     RGBController/RGBControllerKeyNames.cpp). Do not edit by hand.")
    out.append("// </auto-generated>")
    out.append("namespace PadForge.Common.Input.Peripherals.HidFamilies")
    out.append("{")
    out.append("    internal static partial class QmkTables")
    out.append("    {")
    out.append("        /// <summary>The OpenRGB commit the tables were read at.</summary>")
    out.append("        internal const string OpenRgbCommit = \"%s\";" % commit)
    out.append("")
    out.append("        /// <summary>QMKKeycodes.cpp:%d qmk_keynames: a keycode and OpenRGB's" % names_line)
    out.append("        /// name for it, the first of a keycode listed twice.</summary>")
    out.append("        internal static readonly (ushort Keycode, string Name)[] KeyNames =")
    out.append("        {")
    for code, name, line in keynames:
        out.append("            (0x%04X, %s)," % (code, cs_string(name)))
    out.append("        };")
    used = []
    for name in order:
        source = patches[name][1]
        if source not in used:
            used.append(source)
    for source in used:
        cells, line = entries[source]
        cs = "".join(c for c in source.title().replace("_", ""))
        out.append("")
        out.append("        /// <summary>QMKKeychronController_Devices.cpp:%d %s.</summary>" % (line, source))
        out.append("        private static readonly KeychronPatchCell[] %s =" % cs)
        out.append("        {")
        for a, b, c, d in cells:
            out.append("            new(%d, %d, %d, %d)," % (a, b, c, d))
        out.append("        };")
    # The cell lists come first: a static field takes its value in the
    # order the class declares it.
    out.append("")
    out.append("        /// <summary>QMKKeychronController_Devices.cpp:%d keychron_patches, in" % order_line)
    out.append("        /// order: a product ID and the cells its patch moves, source row and")
    out.append("        /// column to row and column.</summary>")
    out.append("        internal static readonly (ushort ProductId, KeychronPatchCell[] Cells)[] KeychronPatches =")
    out.append("        {")
    for name in order:
        pid, source, line = patches[name]
        out.append("            (0x%04X, %s)," % (pid, source.title().replace("_", "")))
    out.append("        };")
    out.append("    }")
    out.append("}")
    text = "\r\n".join(out) + "\r\n"

    if args.check:
        try:
            with open(OUTPUT, encoding="utf-8-sig", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        print("up to date" if current == text else "differs")
        sys.exit(0 if current == text else 1)
    with open(OUTPUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote %s: %d key names, %d patches over %d cell lists" % (OUTPUT, len(keynames), len(order), len(used)))


if __name__ == "__main__":
    main()
