using System;
using System.Collections.Generic;
using PadForge.Common.Input.Peripherals.HidFamilies;

namespace PadForge.Common.Input.Peripherals
{
    /// <summary>
    /// The keyboards (0414:7A3F, 0414:7A43) and backlights (0414:7A42,
    /// 0414:7A44) of Gigabyte's Aorus 17X and 15BKF laptops that OpenRGB's
    /// GigabyteAorusLaptopController lights (#557). The collections are
    /// OpenRGB's registrations (GigabyteAorusLaptopControllerDetect.cpp:58-61),
    /// interface 3, usage page 0xFF01, with 9-byte feature reports and, for
    /// the keyboard, 65-byte output reports.
    ///
    /// <para>The keyboard's lights are its 101 keys, each at its cell of
    /// OpenRGB's grid, each light's address its slot in the custom frame
    /// (aorus_laptop_default_keyboard_layout,
    /// RGBController_GigabyteAorusLaptop.cpp:42-70, generated by
    /// tools/gen_laptop_misc_led_tables.py). The backlight has one light.</para>
    ///
    /// <para>The keyboard has two ways to take colors. OpenRGB's Direct mode
    /// gives the whole keyboard one color and is not marked as saved
    /// (SetDirect, GigabyteAorusLaptopController.cpp:70-103,
    /// RGBController_GigabyteAorusLaptop.cpp:89-97). Its Custom mode colors
    /// key by key and OpenRGB takes it to be saved on its own
    /// (MODE_FLAG_AUTOMATIC_SAVE, line 344, and the comment at lines
    /// 23-28, which says the device keeps five profiles and OpenRGB uses
    /// the first). A picture in one color goes out as Direct, any other as
    /// Custom (SetCustom, GigabyteAorusLaptopController.cpp:187-274): the
    /// Custom mode report, a start report, a read of the answer, a second
    /// report, then the 512 bytes of slots in eight output reports. The
    /// backlight has no Direct mode, so its color goes out as the Static
    /// mode, which OpenRGB marks as saved too (SetMode, lines 105-148): one
    /// of seven colors by index, brightness 0 for black.</para>
    ///
    /// <para>Every report carries a checksum, 0xFF less the sum of bytes 1
    /// to 7. Each mode is sent at the full brightness of 0x32: OpenRGB starts
    /// its modes at half of it, a level the user sets there, while PadForge
    /// puts the level into the colors it sends.</para>
    ///
    /// <para>Since a picture may land in the device's memory, a changed one
    /// goes out once it has held for <see cref="HoldMs"/>, and no sooner
    /// than <see cref="RepaintMs"/> after the one before, for both devices
    /// and both modes.</para>
    ///
    /// <para>Hand-back. Nothing goes out: no reference reads the mode or a
    /// profile back. The keyboard keeps PadForge's last picture until
    /// Gigabyte's program sets another. No source names that program's
    /// process, so none is listed.</para>
    /// </summary>
    internal sealed partial class GigabyteAorusLaptopLighting : IHidLightingFamily
    {
        public static readonly GigabyteAorusLaptopLighting Instance = new();

        internal const string OpenRgbFamily = "GigabyteAorusLaptopController";

        /// <summary>The keyboard detectors (GigabyteAorusLaptopControllerDetect.cpp:48-51).</summary>
        internal const string KeyboardDetector = "DetectGigabyteAorusLaptopKeyboardControllers";

        /// <summary>GIGABYTE_AORUS_LAPTOP_REPORT_SIZE with the report ID 0, and
        /// the output report's length (GigabyteAorusLaptopController.h:18,
        /// .cpp:266-273).</summary>
        internal const int ReportSize = 9;
        internal const int OutputSize = 65;

        /// <summary>GIGABYTE_AORUS_LAPTOP_REPORT_ID, which OpenRGB puts in
        /// byte 1 after the report ID 0 (GigabyteAorusLaptopController.h:19).</summary>
        internal const byte Command = 0x08;

        /// <summary>GIGABYTE_AORUS_LAPTOP_BRIGHTNESS_MAX (GigabyteAorusLaptopController.h:24).</summary>
        internal const byte BrightnessMax = 0x32;

        /// <summary>The Static and Custom modes (GigabyteAorusLaptopController.h:32 and 47).</summary>
        internal const byte StaticMode = 0x01;
        internal const byte CustomMode = 0x33;

        /// <summary>The custom frame's color buffer, 64 slots of four bytes
        /// in eight reports (GigabyteAorusLaptopController.cpp:256-273).</summary>
        internal const int ColorBufferSize = 64 * 8;

        /// <summary>The bounds of a device that stores its pictures
        /// (<see cref="LenovoLegionLighting.HoldMs"/>,
        /// <see cref="LenovoLegionLighting.RepaintMs"/>).</summary>
        internal const int HoldMs = LenovoLegionLighting.HoldMs;
        internal const int RepaintMs = LenovoLegionLighting.RepaintMs;

        public string Name => "Gigabyte Aorus Laptop";

        private readonly Dictionary<ushort, HidLightingModel> _models = new();

        public HidLightingModel Match(HidCollectionInfo collection)
        {
            if (collection == null || collection.FeatureReportLength < ReportSize) return null;
            var registrations = OpenRgbRegistrations.Match(OpenRgbFamily, collection);
            if (registrations.Count == 0) return null;
            var registration = registrations[0];
            bool keyboard = registration.Detector == KeyboardDetector;
            if (keyboard && collection.OutputReportLength < OutputSize) return null;
            lock (_models)
            {
                if (!_models.TryGetValue(collection.ProductId, out var model))
                    _models[collection.ProductId] = model = new HidLightingModel
                    {
                        Family = this,
                        Name = registration.Name,
                        Map = new LightMap(keyboard ? KeyboardLights() : BacklightLights(), "OpenRGB GigabyteAorusLaptopController")
                        {
                            Product = $"gigabyte:0414:{collection.ProductId:X4}",
                        },
                        HoldMs = HoldMs,
                        RepaintMs = RepaintMs,
                        Begin = (_, _) => new Session(keyboard),
                    };
                return model;
            }
        }

        // ─────────────────────────────────────────────
        //  The lights
        // ─────────────────────────────────────────────

        /// <summary>The 101 keys in key order, each with its usage from its
        /// name, its address its slot, and its place on the grid.</summary>
        internal static IReadOnlyList<LightInfo> KeyboardLights()
        {
            var lights = new List<LightInfo>(KeyNames.Length);
            for (int i = 0; i < KeyNames.Length; i++)
            {
                LightInfo light = OpenRgbKeys.TryGet(KeyNames[i], out ushort usage, out var label) && usage != 0
                    ? new LightInfo(Positions[i], LightKind.Key, usage, LightKeySource.Generated)
                    : new LightInfo(Positions[i], LightKind.Other, 0, LightKeySource.None) { Label = label };
                for (int cell = 0; cell < Grid.Length; cell++)
                    if (Grid[cell] == (uint)i)
                    {
                        light = light with { X = cell % GridWidth, Y = cell / GridWidth, Width = 1, Height = 1, HasPosition = true };
                        break;
                    }
                lights.Add(light);
            }
            return lights;
        }

        /// <summary>The backlight's one light, OpenRGB's "Backlight" zone
        /// (RGBController_GigabyteAorusLaptop.cpp:362-391).</summary>
        internal static IReadOnlyList<LightInfo> BacklightLights()
            => new[] { new LightInfo(0, LightKind.Zone, 0, LightKeySource.None) { Zone = 1 } };

        // ─────────────────────────────────────────────
        //  The reports
        // ─────────────────────────────────────────────

        /// <summary>A 9-byte report with its checksum: 0xFF less the sum of
        /// bytes 1 to 7, in bytes (GigabyteAorusLaptopController.cpp:93-100).</summary>
        internal static byte[] Checked(params byte[] body)
        {
            var report = new byte[ReportSize];
            body.CopyTo(report, 1);
            byte checksum = 0xFF;
            for (int i = 1; i < 8; i++) checksum -= report[i];
            report[8] = checksum;
            return report;
        }

        /// <summary>SetDirect: 08 01, the color and the brightness.</summary>
        internal static byte[] DirectFrame(int rgb)
            => Checked(Command, 0x01, (byte)(rgb >> 16), (byte)(rgb >> 8), (byte)rgb, BrightnessMax, 0x00);

        /// <summary>SetCustom's first report: 08 00, the Custom mode, 01, the
        /// brightness, 05 01 (lines 203-222).</summary>
        internal static byte[] CustomFrame() => Checked(Command, 0x00, CustomMode, 0x01, BrightnessMax, 0x05, 0x01);

        /// <summary>SetCustom's start and second reports, as OpenRGB writes
        /// them out, checksums included (lines 227-251).</summary>
        internal static readonly byte[] StartFrame = { 0x00, 0x92, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x6D };
        internal static readonly byte[] SecondFrame = { 0x00, 0x12, 0x00, 0x00, 0x08, 0x00, 0x00, 0x00, 0xE5 };

        /// <summary>SetCustom's eight output reports: the report ID 0, then
        /// 64 bytes of the slots, each slot a zero and the key's color
        /// (lines 256-273).</summary>
        internal static List<byte[]> SlotReports(IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
        {
            var data = new byte[ColorBufferSize];
            int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
            for (int n = 0; n < count; n++)
            {
                int slot = lights[n].Address;
                if (slot < 0 || slot * 4 + 3 >= data.Length) continue;
                data[slot * 4 + 1] = (byte)(colors[n] >> 16);
                data[slot * 4 + 2] = (byte)(colors[n] >> 8);
                data[slot * 4 + 3] = (byte)colors[n];
            }
            var reports = new List<byte[]>(8);
            for (int i = 0; i < 8; i++)
            {
                var report = new byte[OutputSize];
                Array.Copy(data, 64 * i, report, 1, 64);
                reports.Add(report);
            }
            return reports;
        }

        /// <summary>argb_colour_index_data by red, green and blue, each 0 or
        /// 1 (GigabyteAorusLaptopController.cpp:27-33).</summary>
        private static readonly byte[,,] s_index =
        {
            { { 0x01, 0x04 }, { 0x02, 0x04 } },
            { { 0x01, 0x06 }, { 0x05, 0x07 } },
        };

        /// <summary>GetColourIndex (lines 150-185): each channel divided by
        /// the largest, at least 1, in integers.</summary>
        internal static byte ColorIndex(int rgb)
        {
            int r = (rgb >> 16) & 0xFF, g = (rgb >> 8) & 0xFF, b = rgb & 0xFF;
            int largest = r > g ? (r > b ? r : b) : (g > b ? g : b);
            if (largest == 0) largest = 1;
            return s_index[r / largest, g / largest, b / largest];
        }

        /// <summary>The backlight's Static mode, as DeviceUpdateMode sends it
        /// (RGBController_GigabyteAorusLaptop.cpp:474-491): 08 00, the mode,
        /// the speed the Static mode leaves at 0, the brightness, 0 for
        /// black, the color index and the direction the mode leaves at 0,
        /// plus 1.</summary>
        internal static byte[] StaticFrame(int rgb)
        {
            byte brightness = (rgb & 0xFFFFFF) == 0 ? (byte)0 : BrightnessMax;
            return Checked(Command, 0x00, StaticMode, 0x00, brightness, ColorIndex(rgb), 0x01);
        }

        internal sealed class Session : HidLightingSession
        {
            private readonly bool _keyboard;

            public Session(bool keyboard) => _keyboard = keyboard;

            public override bool Feature => true;

            public override byte[][] CrashFrames => Array.Empty<byte[]>();

            public override HidLightingPaint Paint(IHidReportChannel io, Action<int> wait,
                IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
            {
                int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
                if (count == 0) return HidLightingPaint.Sent;
                if (!_keyboard)
                    return io.SetFeature(StaticFrame(colors[0])) ? HidLightingPaint.Sent : HidLightingPaint.Failed;
                bool one = true;
                for (int n = 1; n < count; n++)
                    if ((colors[n] & 0xFFFFFF) != (colors[0] & 0xFFFFFF)) one = false;
                if (one)
                    return io.SetFeature(DirectFrame(colors[0])) ? HidLightingPaint.Sent : HidLightingPaint.Failed;
                var answer = new byte[ReportSize];
                if (!io.SetFeature(CustomFrame()) || !io.SetFeature(StartFrame) || !io.GetFeature(0, answer)
                    || !io.SetFeature(SecondFrame))
                    return HidLightingPaint.Failed;
                foreach (var report in SlotReports(lights, colors))
                    if (!io.WriteOutput(report)) return HidLightingPaint.Failed;
                return HidLightingPaint.Sent;
            }

            public override bool HandBack(IHidReportChannel io, Action<int> wait) => true;
        }
    }
}
