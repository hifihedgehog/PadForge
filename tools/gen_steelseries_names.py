"""The SteelSeries product names, from OpenRGB and rivalcfg (#557).

WHAT IT READS:
- OpenRGB's Controllers/SteelSeriesController/SteelSeriesDevices.h, the
  #define of each product ID, and SteelSeriesControllerDetect.cpp, the name
  each REGISTER_HID_DETECTOR line gives its product.
- rivalcfg's rivalcfg/devices/*.py, the "name" and "product_id" of each
  device profile.

WHAT IT WRITES. PadForge.App/Common/Input/Peripherals/SteelSeriesNames.g.cs:
one row per product ID either reference names, with its name and where the
name was read. OpenRGB's name comes first, from the first line that registers
the product, since OpenRGB is the source the lighting follows. A product
OpenRGB does not register takes rivalcfg's name, from the first profile that
lists it (rivalcfg's devices/__init__.py, which repeats profiles, is not
read). rivalcfg writes a no-break space inside "2.4 GHz", which is written
as a plain space. Lines OpenRGB has commented out are left out.

Usage:
    python tools/gen_steelseries_names.py OPENRGB_ROOT RIVALCFG_ROOT
    python tools/gen_steelseries_names.py OPENRGB_ROOT RIVALCFG_ROOT --check   (compare, write nothing)
"""
import argparse
import glob
import os
import re
import subprocess
import sys

PROJ_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(PROJ_ROOT, "PadForge.App", "Common", "Input", "Peripherals", "SteelSeriesNames.g.cs")

STEELSERIES_VID = 0x1038


def strip_comments(text):
    """The source with its // and /* */ comments blanked out, line breaks
    kept so line numbers still hold."""
    text = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def commit_of(root):
    return subprocess.run(["git", "-C", root, "rev-parse", "HEAD"],
                          capture_output=True, text=True, check=True).stdout.strip()


def line_of(text, index):
    return text.count("\n", 0, index) + 1


def openrgb_names(root):
    ss = os.path.join(root, "Controllers", "SteelSeriesController")
    devices = strip_comments(read(os.path.join(ss, "SteelSeriesDevices.h")))
    defines = {name: int(value, 16)
               for name, value in re.findall(r"#define\s+(\w+)\s+0x([0-9A-Fa-f]+)\b", devices)}
    detect = strip_comments(read(os.path.join(ss, "SteelSeriesControllerDetect.cpp")))
    names = {}
    pattern = re.compile(r"REGISTER_HID_DETECTOR\w*\s*\(\s*\"([^\"]+)\"\s*,\s*\w+\s*,\s*(\w+)\s*,\s*(\w+)")
    for m in pattern.finditer(detect):
        name, vid, pid = m.group(1), m.group(2), m.group(3)
        if vid not in defines or pid not in defines:
            sys.exit("an ID of %s is not defined in SteelSeriesDevices.h" % name)
        if defines[vid] != STEELSERIES_VID:
            continue
        product = defines[pid]
        if product in names:
            continue
        names[product] = (name.strip(), "OpenRGB SteelSeriesControllerDetect.cpp:%d" % line_of(detect, m.start()))
    if not names:
        sys.exit("no registration read")
    return names


def rivalcfg_names(root):
    names = {}
    pattern = re.compile(r"\"name\"\s*:\s*\"([^\"]+)\"\s*,\s*\"vendor_id\"\s*:\s*0x([0-9A-Fa-f]+)\s*,"
                         r"\s*\"product_id\"\s*:\s*0x([0-9A-Fa-f]+)")
    for path in sorted(glob.glob(os.path.join(root, "rivalcfg", "devices", "*.py"))):
        base = os.path.basename(path)
        if base == "__init__.py":
            continue
        text = read(path)
        for m in pattern.finditer(text):
            if int(m.group(2), 16) != STEELSERIES_VID:
                continue
            product = int(m.group(3), 16)
            if product in names:
                continue
            name = m.group(1).replace(chr(0xA0), " ").strip()
            names[product] = (name, "rivalcfg devices/%s:%d" % (base, line_of(text, m.start())))
    if not names:
        sys.exit("no rivalcfg profile read")
    return names


def cs_string(text):
    return "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"") + "\""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("openrgb")
    parser.add_argument("rivalcfg")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    openrgb = openrgb_names(args.openrgb)
    rivalcfg = rivalcfg_names(args.rivalcfg)
    rows = dict(rivalcfg)
    rows.update(openrgb)
    for name, _ in rows.values():
        if any(ord(c) > 0x7E or ord(c) < 0x20 for c in name):
            sys.exit("a name holds a character outside printable ASCII: %r" % name)

    out = []
    out.append("// <auto-generated>")
    out.append("//     Generated by tools/gen_steelseries_names.py from OpenRGB at %s" % commit_of(args.openrgb)[:10])
    out.append("//     (Controllers/SteelSeriesController: SteelSeriesDevices.h and")
    out.append("//     SteelSeriesControllerDetect.cpp) and rivalcfg at %s" % commit_of(args.rivalcfg)[:10])
    out.append("//     (rivalcfg/devices). Do not edit by hand.")
    out.append("// </auto-generated>")
    out.append("namespace PadForge.Common.Input.Peripherals")
    out.append("{")
    out.append("    internal static partial class SteelSeriesNames")
    out.append("    {")
    out.append("        /// <summary>The OpenRGB and rivalcfg commits the names were read at.</summary>")
    out.append("        internal const string OpenRgbCommit = \"%s\";" % commit_of(args.openrgb))
    out.append("        internal const string RivalcfgCommit = \"%s\";" % commit_of(args.rivalcfg))
    out.append("")
    out.append("        /// <summary>Each product ID's name and the line it was read from, by product ID.</summary>")
    out.append("        internal static readonly (ushort ProductId, string Name, string Source)[] All =")
    out.append("        {")
    for product in sorted(rows):
        name, source = rows[product]
        out.append("            (0x%04X, %s, %s)," % (product, cs_string(name), cs_string(source)))
    out.append("        };")
    out.append("    }")
    out.append("}")
    text = "\r\n".join(out) + "\r\n"

    if args.check:
        current = open(OUTPUT, "rb").read().decode("utf-8") if os.path.exists(OUTPUT) else ""
        if current != text:
            print("SteelSeriesNames.g.cs differs from the references")
            return 1
        print("up to date")
        return 0
    with open(OUTPUT, "wb") as f:
        f.write(text.encode("utf-8"))
    print("wrote %d names" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
