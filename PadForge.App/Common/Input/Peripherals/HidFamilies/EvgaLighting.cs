        /// <summary>The keyboard's lights in LED order, each light's address
        /// its LED index. A key named by OpenRGB's key names has its usage, a
        /// side light is an edge light, and a macro or feature key no source
        /// gives a usage is a key Map Key Lights can name. The keys sit on
        /// their grid, and the Z20's three extra zones in a row each below
        /// it.</summary>
        internal static IReadOnlyList<LightInfo> KeyboardLights(bool z20)
        {
            int count = z20 ? FullSizeKeys + Z20ExtraKeys : FullSizeKeys;
            var lights = new List<LightInfo>(count);
            for (int i = 0; i < count; i++)
            {
                string name = LedNames[i];
                LightInfo light;
                if (OpenRgbKeys.TryGet(name, out ushort usage, out var label) && usage != 0)
                    light = new LightInfo(i, LightKind.Key, usage, LightKeySource.Generated);
                else if (label != LightLabel.None)
                    light = new LightInfo(i, LightKind.Other, 0, LightKeySource.None) { Label = label };
                else if (name.StartsWith("Key: Right LED", StringComparison.Ordinal) || name.StartsWith("Key: Left LED", StringComparison.Ordinal))
                    light = new LightInfo(i, LightKind.Edge, 0, LightKeySource.None);
                else
                    light = new LightInfo(i, LightKind.Key, 0, LightKeySource.None);
                lights.Add(Place(light, i));
            }
            return lights;
        }

        private static LightInfo Place(LightInfo light, int index)
        {
            if (index < FullSizeKeys)
            {
                for (int cell = 0; cell < KeyboardGrid.Length; cell++)
                    if (KeyboardGrid[cell] == (uint)index)
                        return light with { X = cell % 21, Y = cell / 21, Width = 1, Height = 1, HasPosition = true };
                return light;
            }
            // Zone z of the Z20's extra zones starts at LED 108 + 9z
            // (RGBController_EVGAKeyboard.cpp:27-32 and 453-464).
            int zone = (index - FullSizeKeys) / 9;
            int led = (index - FullSizeKeys) % 9;
            for (int cell = 0; cell < 9; cell++)
                if (Z20ExtraZones[zone * 9 + cell] == (uint)led)
                    return light with { X = cell, Y = 6 + zone, Width = 1, Height = 1, HasPosition = true };
            return light;
        }

        /// <summary>A checksum of the keyboard's: 0 less every byte from the
        /// zone byte to the end (GetChecksum, EVGAKeyboardController.cpp:316-326,
        /// called on 784 bytes from byte 8).</summary>
        internal static byte Checksum(byte[] report)
        {
            byte sum = 0;
            for (int i = ZoneByte; i < report.Length; i++) sum -= report[i];
            return sum;
        }

        /// <summary>SetLedsDirect's report: 06 EA 02 01, then at 8 plus four
        /// times each LED's packet map slot its full brightness and color,
        /// and the checksum in byte 7.</summary>
        internal static byte[] DirectFrame(IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
        {
            var report = new byte[KeyboardReportSize];
            report[0] = KeyboardReportId;
            report[1] = 0xEA;
            report[2] = 0x02;
            report[3] = 0x01;
            int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
            for (int n = 0; n < count; n++)
            {
                int led = lights[n].Address;
                if (led < 0 || led >= PacketMap.Length) continue;
                int at = ZoneByte + PacketMap[led] * 4;
                report[at] = 0xFF;
                report[at + 1] = (byte)(colors[n] >> 16);
                report[at + 2] = (byte)(colors[n] >> 8);
                report[at + 3] = (byte)colors[n];
            }
            report[ChecksumByte] = Checksum(report);
            return report;
        }

        /// <summary>SetHWModes' report, 06 EA 02 and nothing else.</summary>
        internal static byte[] HardwareModesFrame()
        {
            var report = new byte[KeyboardReportSize];
            report[0] = KeyboardReportId;
            report[1] = 0xEA;
            report[2] = 0x02;
            return report;
        }

        internal sealed class KeyboardSession : HidLightingSession
        {
            private byte[][] _crash = Array.Empty<byte[]>();

            public override bool Feature => true;

            /// <summary>The hardware modes report, once a picture may have
            /// gone out.</summary>
            public override byte[][] CrashFrames => _crash;

            public override HidLightingPaint Paint(IHidReportChannel io, Action<int> wait,
                IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
            {
                // Marked first: a write that reports a failure may still
                // have landed.
                if (_crash.Length == 0) _crash = new[] { HardwareModesFrame() };
                return io.SetFeature(DirectFrame(lights, colors)) ? HidLightingPaint.Sent : HidLightingPaint.Failed;
            }

            public override bool HandBack(IHidReportChannel io, Action<int> wait)
            {
                if (_crash.Length == 0) return true;
                if (!io.SetFeature(HardwareModesFrame())) return false;
                _crash = Array.Empty<byte[]>();
                return true;
            }
        }

