        internal static readonly int[] X12LedSlots = { 0, 2, 3 };

        /// <summary>The bounds of a mouse that saves its colors
        /// (<see cref="LenovoLegionLighting.HoldMs"/>,
        /// <see cref="LenovoLegionLighting.RepaintMs"/>), and PadForge's
        /// bound for a mode that saves nothing
        /// (<see cref="AsusTufLaptopLighting.RepaintMs"/>).</summary>
        internal const int HoldMs = LenovoLegionLighting.HoldMs;
        internal const int RepaintMs = LenovoLegionLighting.RepaintMs;
        internal const int VolatileRepaintMs = AsusTufLaptopLighting.RepaintMs;

        public string Name => "EVGA";

        private readonly Dictionary<ushort, HidLightingModel> _models = new();

        public HidLightingModel Match(HidCollectionInfo collection)
        {
            if (collection == null) return null;
            foreach (var registration in OpenRgbRegistrations.Match(OpenRgbFamily, collection))
            {
                int length = registration.Detector switch
                {
                    KeyboardDetector => KeyboardReportSize,
                    WiredMouseDetector or WirelessMouseDetector => MouseReportSize,
                    X12Detector => X12ReportSize,
                    _ => int.MaxValue,
                };
                if (collection.FeatureReportLength < length) continue;
                lock (_models)
                {
                    if (!_models.TryGetValue(collection.ProductId, out var model))
                        _models[collection.ProductId] = model = Model(registration, collection.ProductId);
                    return model;
                }
            }
            return null;
        }

        private HidLightingModel Model(OpenRgbRegistration registration, ushort productId)
        {
            var model = registration.Detector switch
            {
                KeyboardDetector => new HidLightingModel
                {
                    Map = new LightMap(KeyboardLights(productId is Z20AnsiPid or Z20UkPid), "OpenRGB EVGAKeyboardController"),
                    RepaintMs = VolatileRepaintMs,
                    Begin = (_, _) => new KeyboardSession(),
                },
                X12Detector => new HidLightingModel
                {
                    Map = new LightMap(X12Lights(), "OpenRGB EVGAX12Controller"),
                    RepaintMs = VolatileRepaintMs,
                    Begin = (io, wait) => X12Session.Begin(io, wait),
                },
                _ => new HidLightingModel
                {
                    Map = new LightMap(MouseLights(), "OpenRGB EVGAMouseController"),
                    HoldMs = HoldMs,
                    RepaintMs = RepaintMs,
                    Begin = (io, wait) => MouseSession.Begin(io, wait,
                        registration.Detector == WirelessMouseDetector ? Wireless : (byte)0),
                },
            };
            return new HidLightingModel
            {
                Family = this,
                Name = registration.Name,
                Map = new LightMap(model.Map.Lights, model.Map.Source) { Product = $"evga:3842:{productId:X4}" },
                HoldMs = model.HoldMs,
                RepaintMs = model.RepaintMs,
                Begin = model.Begin,
            };
        }

