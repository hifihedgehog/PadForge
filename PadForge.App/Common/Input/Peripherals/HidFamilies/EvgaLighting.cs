        /// <summary>GetReport's request (EVGAX12Controller.cpp:220-228).</summary>
        internal static byte[] X12Request(byte command) => X12Frame(X12Get, command);

        /// <summary>SetModeReport's report: 07 EA 02 01 and each slot's mode
        /// from byte 4 (lines 110-126).</summary>
        internal static byte[] X12ModeFrame(IReadOnlyList<byte> slotModes)
        {
            var report = X12Frame(X12Set, X12CommandMode);
            for (int slot = 0; slot < X12Slots; slot++) report[4 + slot] = slotModes[slot];
            return report;
        }

        /// <summary>SetStaticReport's report: 07 EA 02 02, each slot's
        /// brightness and color, four bytes from byte 4, and 01 in bytes 20
        /// to 23 (lines 159-181).</summary>
        internal static byte[] X12StaticFrame(IReadOnlyList<(byte Brightness, int Rgb)> slots)
        {
            var report = X12Frame(X12Set, X12CommandStatic);
            for (int slot = 0; slot < X12Slots; slot++)
            {
                report[20 + slot] = 0x01;
                int at = 4 + slot * 4;
                report[at] = slots[slot].Brightness;
                report[at + 1] = (byte)(slots[slot].Rgb >> 16);
                report[at + 2] = (byte)(slots[slot].Rgb >> 8);
                report[at + 3] = (byte)slots[slot].Rgb;
            }
            return report;
        }

        internal sealed class X12Session : HidLightingSession
        {
            private readonly byte[] _modes;
            private readonly (byte Brightness, int Rgb)[] _slots;
            private bool _active;
            private byte[][] _crash = Array.Empty<byte[]>();

            private X12Session(byte[] modes, (byte, int)[] slots)
            {
                _modes = modes;
                _slots = slots;
            }

            public override bool Feature => true;

            public override byte[][] CrashFrames => _crash;

            /// <summary>GetReport: the request, then up to five reads 5 ms
            /// apart until one carries the header and the command. Null when
            /// a write or a read failed or no answer came.</summary>
            internal static byte[] Read(IHidReportChannel io, Action<int> wait, byte command)
            {
                if (!io.SetFeature(X12Request(command))) return null;
                var answer = new byte[X12ReportSize];
                for (int attempt = 0; attempt < X12ReadAttempts; attempt++)
                {
                    wait(X12WaitMs);
                    Array.Clear(answer);
                    answer[0] = X12ReportId;
                    if (!io.GetFeature(X12ReportId, answer)) return null;
                    if (answer[1] == X12Header && answer[3] == command) return answer;
                }
                return null;
            }

            /// <summary>A session on the slots' modes and static colors, or
            /// null when the mouse did not answer them.</summary>
            internal static HidLightingSession Begin(IHidReportChannel io, Action<int> wait)
            {
                var modes = Read(io, wait, X12CommandMode);
                if (modes == null) return null;
                var colors = Read(io, wait, X12CommandStatic);
                if (colors == null) return null;
                var savedModes = new byte[X12Slots];
                var savedSlots = new (byte, int)[X12Slots];
                for (int slot = 0; slot < X12Slots; slot++)
                {
                    savedModes[slot] = modes[4 + slot];
                    int at = 4 + slot * 4;
                    savedSlots[slot] = (colors[at], colors[at + 1] << 16 | colors[at + 2] << 8 | colors[at + 3]);
                }
                return new X12Session(savedModes, savedSlots);
            }

            /// <summary>Writes a static report and reads it back, up to three
            /// tries, until the four slots read as written.</summary>
            private static bool WriteStatic(IHidReportChannel io, Action<int> wait, byte[] report)
            {
                for (int attempt = 0; attempt < X12WriteAttempts; attempt++)
                {
                    if (!io.SetFeature(report)) return false;
                    wait(X12WaitMs);
                    var reply = Read(io, wait, X12CommandStatic);
                    if (reply != null && reply.AsSpan(4, X12Slots * 4).SequenceEqual(report.AsSpan(4, X12Slots * 4)))
                        return true;
                }
                return false;
            }

            internal byte[] RestoreStatic() => X12StaticFrame(_slots);

            internal byte[] RestoreModes() => X12ModeFrame(_modes);

            public override HidLightingPaint Paint(IHidReportChannel io, Action<int> wait,
                IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
            {
                // Marked first: a write that reports a failure may still
                // have landed.
                if (_crash.Length == 0) _crash = new[] { RestoreStatic(), RestoreModes() };
                var slots = new (byte Brightness, int Rgb)[X12Slots];
                int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
                for (int n = 0; n < count; n++)
                {
                    int slot = lights[n].Address;
                    if (slot >= 0 && slot < X12Slots) slots[slot] = (X12BrightnessMax, colors[n]);
                }
                if (!WriteStatic(io, wait, X12StaticFrame(slots))) return HidLightingPaint.Failed;
                if (!_active)
                {
                    wait(X12WaitMs);
                    var modes = new byte[X12Slots];
                    foreach (int slot in X12LedSlots) modes[slot] = X12ModeStatic;
                    if (!io.SetFeature(X12ModeFrame(modes))) return HidLightingPaint.Failed;
                    _active = true;
                }
                return HidLightingPaint.Sent;
            }

            public override bool HandBack(IHidReportChannel io, Action<int> wait)
            {
                if (_crash.Length == 0) return true;
                if (!WriteStatic(io, wait, RestoreStatic())) return false;
                wait(X12WaitMs);
                if (!io.SetFeature(RestoreModes())) return false;
                _crash = Array.Empty<byte[]>();
                _active = false;
                return true;
            }
        }
    }
