        /// <summary>Front, wheel and the logo, OpenRGB's three zones of one
        /// light each, the address the light's index.</summary>
        internal static IReadOnlyList<LightInfo> MouseLights() => new[]
        {
            new LightInfo(0, LightKind.Zone, 0, LightKeySource.None) { Zone = 1 },
            new LightInfo(1, LightKind.Zone, 0, LightKeySource.None) { Zone = 2 },
            new LightInfo(2, LightKind.Logo, 0, LightKeySource.None),
        };

        /// <summary>RefreshDeviceState's request: 00 00 00, the connection
        /// type, 1D 02 80 02, the light.</summary>
        internal static byte[] MouseReadFrame(byte connection, int led)
        {
            var report = new byte[MouseReportSize];
            report[3] = connection;
            report[4] = 0x1D;
            report[5] = 0x02;
            report[6] = 0x80;
            report[7] = 0x02;
            report[MouseLedIndexByte] = (byte)led;
            return report;
        }

        /// <summary>SetMode's report: 00 00 00 00 1D 02 81 01, the light,
        /// the mode. Byte 3 stays 0 whatever the connection.</summary>
        internal static byte[] MouseModeFrame(int led, byte mode)
        {
            var report = new byte[MouseReportSize];
            report[4] = 0x1D;
            report[5] = 0x02;
            report[6] = 0x81;
            report[7] = 0x01;
            report[MouseLedIndexByte] = (byte)led;
            report[MouseModeByte] = mode;
            return report;
        }

        /// <summary>SetLed's report: 00 (A1 to activate) 00, the connection
        /// type, 1D 02 00 02, the light, the mode, the brightness, the speed,
        /// the color count up to 7 and the colors.</summary>
        internal static byte[] MouseColorFrame(byte connection, int led, byte mode, byte brightness, byte speed,
            IReadOnlyList<int> colors, bool activate = false)
        {
            var report = new byte[MouseReportSize];
            report[1] = activate ? (byte)0xA1 : (byte)0x00;
            report[3] = connection;
            report[4] = 0x1D;
            report[5] = 0x02;
            report[6] = 0x00;
            report[7] = 0x02;
            report[MouseLedIndexByte] = (byte)led;
            report[MouseModeByte] = mode;
            report[MouseBrightnessByte] = brightness;
            report[MouseSpeedByte] = speed;
            int count = Math.Min(colors?.Count ?? 0, 7);
            report[MouseColorCountByte] = (byte)count;
            for (int i = 0; i < count; i++)
            {
                report[MouseRedByte + i * 3] = (byte)(colors[i] >> 16);
                report[MouseRedByte + 1 + i * 3] = (byte)(colors[i] >> 8);
                report[MouseRedByte + 2 + i * 3] = (byte)colors[i];
            }
            return report;
        }

        /// <summary>The answer that means "not ready yet", and the one that
        /// means the mouse sleeps, by their first eight bytes
        /// (IsResponseNotReadyPacket and IsAsleepPacket,
        /// EVGAMouseController.cpp:322-343).</summary>
        internal static bool NotReady(byte[] answer) => StartsWith(answer, 0x00, 0xA0, 0x00, 0x02, 0x1D, 0x02, 0x80, 0x02);
        internal static bool Asleep(byte[] answer) => StartsWith(answer, 0x00, 0xA4, 0x00, 0x02, 0x1D, 0x02, 0x80, 0x02);

        private static bool StartsWith(byte[] answer, params byte[] head)
        {
            if (answer == null || answer.Length < head.Length) return false;
            for (int i = 0; i < head.Length; i++)
                if (answer[i] != head[i]) return false;
            return true;
        }

        /// <summary>One light's state as the mouse answered it.</summary>
        internal sealed record MouseState(byte Mode, byte Brightness, byte Speed, int[] Colors);

        internal sealed class MouseSession : HidLightingSession
        {
            private readonly byte _connection;
            private readonly MouseState[] _saved;
            private bool _static;
            private byte[][] _crash = Array.Empty<byte[]>();

            private MouseSession(byte connection, MouseState[] saved)
            {
                _connection = connection;
                _saved = saved;
            }

            public override bool Feature => true;

            /// <summary>The frames that write back what the session read,
            /// once a picture may have gone out.</summary>
            public override byte[][] CrashFrames => _crash;

            internal IReadOnlyList<MouseState> Saved => _saved;

            /// <summary>The wait between packets, on the receiver only.</summary>
            private static void Pause(byte connection, Action<int> wait)
            {
                if (connection == Wireless) wait(WirelessWaitMs);
            }

            /// <summary>ReadPacketOrLogErrors: a read, asked again while the
            /// mouse answers that it is not ready, up to 100 reads. Null when
            /// a read failed, the mouse never got ready, or it sleeps.</summary>
            internal static byte[] ReadAnswer(IHidReportChannel io, Action<int> wait, byte connection)
            {
                var answer = new byte[MouseReportSize];
                Pause(connection, wait);
                if (!io.GetFeature(0, answer)) return null;
                for (int attempts = 1; attempts < MaxAttempts && NotReady(answer); attempts++)
                {
                    Pause(connection, wait);
                    if (!io.GetFeature(0, answer)) return null;
                }
                return NotReady(answer) || Asleep(answer) ? null : answer;
            }

            /// <summary>A session on the three lights' states, or null when
            /// one of them did not answer or answered no color, which the
            /// mouse does while it sleeps (EVGAMouseController.cpp:258-263).</summary>
            internal static HidLightingSession Begin(IHidReportChannel io, Action<int> wait, byte connection)
            {
                var saved = new MouseState[MouseLeds];
                for (int led = 0; led < MouseLeds; led++)
                {
                    if (!io.SetFeature(MouseReadFrame(connection, led))) return null;
                    Pause(connection, wait);
                    var answer = ReadAnswer(io, wait, connection);
                    if (answer == null) return null;
                    int count = Math.Min((int)answer[MouseColorCountByte], 7);
                    if (count == 0) return null;
                    var colors = new int[count];
                    for (int i = 0; i < count; i++)
                        colors[i] = answer[MouseRedByte + i * 3] << 16 | answer[MouseRedByte + 1 + i * 3] << 8
                                    | answer[MouseRedByte + 2 + i * 3];
                    saved[led] = new MouseState(answer[MouseModeByte], answer[MouseBrightnessByte], answer[MouseSpeedByte], colors);
                }
                return new MouseSession(connection, saved);
            }

            /// <summary>What puts every light back as the session found it:
            /// each light's mode, then each light's mode again with its
            /// brightness, speed and colors, twice with the second to activate
            /// where that mode is breathing.</summary>
            internal List<byte[]> RestoreFrames()
            {
                var frames = new List<byte[]>();
                for (int led = 0; led < MouseLeds; led++) frames.Add(MouseModeFrame(led, _saved[led].Mode));
                for (int led = 0; led < MouseLeds; led++)
                {
                    var s = _saved[led];
                    frames.Add(MouseColorFrame(_connection, led, s.Mode, s.Brightness, s.Speed, s.Colors));
                    if (s.Mode == MouseBreathing)
                        frames.Add(MouseColorFrame(_connection, led, s.Mode, s.Brightness, s.Speed, s.Colors, activate: true));
                }
                return frames;
            }

            public override HidLightingPaint Paint(IHidReportChannel io, Action<int> wait,
                IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
            {
                // Marked first: a write that reports a failure may still
                // have landed.
                if (_crash.Length == 0) _crash = RestoreFrames().ToArray();
                if (!_static)
                {
                    for (int led = 0; led < MouseLeds; led++)
                    {
                        if (!io.SetFeature(MouseModeFrame(led, MouseStatic))) return HidLightingPaint.Failed;
                        var answer = new byte[MouseReportSize];
                        if (!io.GetFeature(0, answer)) return HidLightingPaint.Failed;
                    }
                    _static = true;
                }
                int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
                for (int n = 0; n < count; n++)
                {
                    int led = lights[n].Address;
                    if (led < 0 || led >= MouseLeds) continue;
                    if (!io.SetFeature(MouseColorFrame(_connection, led, MouseStatic, MouseBrightness, 0, new[] { colors[n] })))
                        return HidLightingPaint.Failed;
                    if (ReadAnswer(io, wait, _connection) == null) return HidLightingPaint.Failed;
                }
                return HidLightingPaint.Sent;
            }

            public override bool HandBack(IHidReportChannel io, Action<int> wait)
            {
                if (_crash.Length == 0) return true;
                var frames = RestoreFrames();
                for (int i = 0; i < MouseLeds; i++)
                {
                    if (!io.SetFeature(frames[i])) return false;
                    if (!io.GetFeature(0, new byte[MouseReportSize])) return false;
                }
                for (int i = MouseLeds; i < frames.Count; i++)
                {
                    if (!io.SetFeature(frames[i])) return false;
                    if (ReadAnswer(io, wait, _connection) == null) return false;
                }
                _crash = Array.Empty<byte[]>();
                _static = false;
                return true;
            }
        }

