        private static byte[] FromHex(string hex)
        {
            var bytes = new byte[hex.Length / 2];
            for (int i = 0; i < bytes.Length; i++) bytes[i] = Convert.ToByte(hex.Substring(i * 2, 2), 16);
            return bytes;
        }

        [Theory]
        [MemberData(nameof(OpenRgbReports))]
        public void AKeysReport_IsOpenRgbsByteForByte(int key, int rgb, string expected)
        {
            var report = StreamDeckLighting.KeyReport(key, rgb);
            Assert.Equal(1024, report.Length);
            var head = FromHex(expected);
            Assert.Equal(Hex(head), Hex(report, head.Length));
            Assert.All(report.Skip(head.Length), b => Assert.Equal(0, b));
        }

        [Fact]
        public void TheJpeg_IsStbsAtQuality95_NoSubsampling_AndFitsOnePage()
        {
            var jpeg = StreamDeckLighting.Image(0x123456);
            // SOI, JFIF, SOF0 72 by 72 with three components sampled 1x1
            // (0x11), as stb writes at a quality above 90
            // (stb_image_write.h:1479 and 1499-1502), and EOI.
            Assert.Equal("FF D8 FF E0", Hex(jpeg, 4));
            int sof = IndexOf(jpeg, 0xFF, 0xC0);
            Assert.Equal("FF C0 00 11 08 00 48 00 48 03 01 11 00 02 11 01 03 11 01", Hex(jpeg.Skip(sof).ToArray(), 19));
            Assert.Equal("FF D9", Hex(jpeg.Skip(jpeg.Length - 2).ToArray()));
            Assert.True(jpeg.Length <= 1024 - 8);
            // The header carries the length, low byte first, and page 0 marked last.
            var report = StreamDeckLighting.KeyReport(5, 0x123456);
            Assert.Equal($"02 07 05 01 {jpeg.Length & 0xFF:X2} {jpeg.Length >> 8:X2} 00 00", Hex(report, 8));
        }

