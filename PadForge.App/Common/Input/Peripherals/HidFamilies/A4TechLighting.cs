using System;
using System.Collections.Generic;
using PadForge.Common.Input.Peripherals.HidFamilies;

namespace PadForge.Common.Input.Peripherals
{
    /// <summary>
    /// A4Tech's Bloody B820R keyboard (09DA:FA10), its W60 Pro, W70 Max,
    /// W90 Max and W90 Pro mice and its MP 50RS mouse pad, lit as OpenRGB's
    /// A4TechController lights them (#557). The collections are OpenRGB's
    /// registrations (BloodyB820RControllerDetect.cpp:40,
    /// BloodyMouseControllerDetect.cpp:40-44), interface 2 on vendor usage
    /// pages, with 64-byte feature reports whose report ID is 7.
    ///
    /// <para>The lights are OpenRGB's: the B820R's 104 keys on their grid
    /// (RGBController_BloodyB820R.cpp:18-139), the mice's zones and the pad's
    /// ten lights (RGBController_BloodyMouse.cpp:14-48), each light's
    /// address its LED number, all generated by
    /// tools/gen_laptop_misc_led_tables.py. A zone of one light is a zone,
    /// except the logo, and a strip of several is an edge light.</para>
    ///
    /// <para>Before the first picture a session takes control of the
    /// device's lights with the two control reports OpenRGB sends when it
    /// opens one, 07 03 06 01 and then the same with 01 in byte 8 and 00 in
    /// byte 3 (SendControlPacket, BloodyB820RController.cpp:29 and 61-71;
    /// InitDevice, BloodyMouseController.cpp:58-68, the same two reports). A
    /// picture then goes out as OpenRGB's Direct mode sends it: the B820R's
    /// reds, greens and blues in two reports each, 58 keys to the first
    /// (SetLEDDirect, BloodyB820RController.cpp:73-110), a mouse's colors in
    /// one report at three bytes per LED number (SetLedsDirect,
    /// BloodyMouseController.cpp:70-84). OpenRGB marks Direct as a mode that
    /// saves nothing ("@save :x:").</para>
    ///
    /// <para>Hand-back. The control reports again with 00 in byte 8, which
    /// OpenRGB sends to the B820R when it lets it go
    /// (BLOODY_B820R_RELEASE_CONTROL, BloodyB820RController.cpp:32-36 and
    /// BloodyB820RController.h:26-27). OpenRGB's mouse controller sends no
    /// release, and takes control with the B820R's very reports, so its
    /// release is the B820R's.</para>
    ///
    /// <para>No source names a process of A4Tech's Bloody software, so no
    /// program is listed.</para>
    /// </summary>
    internal sealed partial class A4TechLighting : IHidLightingFamily
    {
        public static readonly A4TechLighting Instance = new();

        internal const string OpenRgbFamily = "A4TechController";

        internal const string KeyboardDetector = "DetectBloodyB820R";

        /// <summary>The product IDs (BloodyMouseController.h:21-29).</summary>
        internal const ushort W60ProPid = 0x37EA;
        internal const ushort W70MaxPid = 0x79EF;
        internal const ushort W90MaxPid = 0x3666;
        internal const ushort W90ProPid = 0x39B6;
        internal const ushort Mp50rsPid = 0xFA60;

        /// <summary>The report's length and ID, and its mode and data bytes
        /// (BloodyB820RController.h:22-27, BloodyMouseController.h:32-48).</summary>
        internal const int PacketSize = 64;
        internal const byte ReportId = 0x07;
        internal const int ModeByte = 3;
        internal const int DataByte = 8;

        /// <summary>BLOODY_B820R_RGB_BUFFER_SIZE and BLOODY_B820R_RGB_OFFSET
        /// (BloodyB820RController.h:20-21).</summary>
        internal const int KeysPerReport = 58;
        internal const int RgbOffset = 6;

        /// <summary>The shortest time between two pictures, PadForge's bound
        /// for a mode that saves nothing
        /// (<see cref="AsusTufLaptopLighting.RepaintMs"/>).</summary>
        internal const int RepaintMs = AsusTufLaptopLighting.RepaintMs;

        public string Name => "A4Tech Bloody";

        private readonly Dictionary<ushort, HidLightingModel> _models = new();

        public HidLightingModel Match(HidCollectionInfo collection)
        {
            if (collection == null || collection.FeatureReportLength < PacketSize) return null;
            var registrations = OpenRgbRegistrations.Match(OpenRgbFamily, collection);
            if (registrations.Count == 0) return null;
            bool keyboard = registrations[0].Detector == KeyboardDetector;
            var lights = keyboard ? KeyboardLights() : MouseLights(collection.ProductId);
            if (lights == null) return null;
            lock (_models)
            {
                if (!_models.TryGetValue(collection.ProductId, out var model))
                    _models[collection.ProductId] = model = new HidLightingModel
                    {
                        Family = this,
                        Name = registrations[0].Name,
                        Map = new LightMap(lights, "OpenRGB A4TechController") { Product = $"a4tech:09DA:{collection.ProductId:X4}" },
                        RepaintMs = RepaintMs,
                        Begin = (_, _) => new Session(keyboard),
                    };
                return model;
            }
        }

        // ─────────────────────────────────────────────
        //  The lights
        // ─────────────────────────────────────────────

        /// <summary>The B820R's keys in LED order, each with its usage from
        /// its name and its place on the grid.</summary>
        internal static IReadOnlyList<LightInfo> KeyboardLights()
        {
            var lights = new List<LightInfo>(B820rKeyNames.Length);
            for (int i = 0; i < B820rKeyNames.Length; i++)
            {
                LightInfo light = OpenRgbKeys.TryGet(B820rKeyNames[i], out ushort usage, out var label) && usage != 0
                    ? new LightInfo(i, LightKind.Key, usage, LightKeySource.Generated)
                    : new LightInfo(i, LightKind.Other, 0, LightKeySource.None) { Label = label };
                for (int cell = 0; cell < B820rGrid.Length; cell++)
                    if (B820rGrid[cell] == (uint)i)
                    {
                        light = light with { X = cell % 21, Y = cell / 21, Width = 1, Height = 1, HasPosition = true };
                        break;
                    }
                lights.Add(light);
            }
            return lights;
        }

        /// <summary>The zones of a mouse or the pad, by product ID, as
        /// SetupZones picks them (RGBController_BloodyMouse.cpp:110-126).
        /// Null for an ID it has none for.</summary>
        internal static (string Name, byte[] Leds)[] LayoutOf(ushort productId) => productId switch
        {
            W60ProPid => W60Pro,
            W70MaxPid or W90MaxPid or W90ProPid => W90Max,
            Mp50rsPid => Mp50rs,
            _ => null,
        };

        /// <summary>Each zone's lights in OpenRGB's order, each light's
        /// address its LED number: the logo a logo light, another zone of
        /// one light a zone, a zone of several an edge light each.</summary>
        internal static IReadOnlyList<LightInfo> MouseLights(ushort productId)
        {
            var layout = LayoutOf(productId);
            if (layout == null) return null;
            var lights = new List<LightInfo>();
            int zone = 0;
            foreach (var (name, leds) in layout)
            {
                if (leds.Length == 1)
                {
                    lights.Add(name == "Logo"
                        ? new LightInfo(leds[0], LightKind.Logo, 0, LightKeySource.None)
                        : new LightInfo(leds[0], LightKind.Zone, 0, LightKeySource.None) { Zone = ++zone });
                    continue;
                }
                foreach (byte led in leds)
                    lights.Add(new LightInfo(led, LightKind.Edge, 0, LightKeySource.None));
            }
            return lights;
        }

        // ─────────────────────────────────────────────
        //  The reports
        // ─────────────────────────────────────────────

        private static byte[] Report(byte mode)
        {
            var report = new byte[PacketSize];
            report[0] = ReportId;
            report[1] = 0x03;
            report[2] = 0x06;
            report[ModeByte] = mode;
            return report;
        }

        /// <summary>SendControlPacket's two reports: 07 03 06 01, then
        /// 07 03 06 00 with <paramref name="data"/> in byte 8: 1 takes
        /// control and 0 lets it go.</summary>
        internal static byte[][] ControlFrames(byte data)
        {
            var second = Report(0x00);
            second[DataByte] = data;
            return new[] { Report(0x01), second };
        }

        /// <summary>SetLEDDirect's six reports: red, green and blue, each
        /// in two, modes 07 to 0C in the order r1, r2, g1, g2, b1, b2, each
        /// key at byte 6 plus its number modulo 58 of the report its number
        /// falls in.</summary>
        internal static List<byte[]> KeyboardFrames(IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
        {
            var r1 = Report(0x07);
            var r2 = Report(0x08);
            var g1 = Report(0x09);
            var g2 = Report(0x0A);
            var b1 = Report(0x0B);
            var b2 = Report(0x0C);
            int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
            for (int n = 0; n < count; n++)
            {
                int i = lights[n].Address;
                if (i < 0 || i >= 2 * KeysPerReport) continue;
                bool second = i >= KeysPerReport;
                int at = RgbOffset + i % KeysPerReport;
                (second ? r2 : r1)[at] = (byte)(colors[n] >> 16);
                (second ? g2 : g1)[at] = (byte)(colors[n] >> 8);
                (second ? b2 : b1)[at] = (byte)colors[n];
            }
            return new List<byte[]> { r1, r2, g1, g2, b1, b2 };
        }

        /// <summary>SetLedsDirect's report: 07 03 06 02, each LED's color at
        /// byte 8 plus three times its number.</summary>
        internal static byte[] MouseFrame(IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
        {
            var report = Report(0x02);
            int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
            for (int n = 0; n < count; n++)
            {
                int at = DataByte + 3 * lights[n].Address;
                if (at < DataByte || at + 2 >= PacketSize) continue;
                report[at] = (byte)(colors[n] >> 16);
                report[at + 1] = (byte)(colors[n] >> 8);
                report[at + 2] = (byte)colors[n];
            }
            return report;
        }

        internal sealed class Session : HidLightingSession
        {
            private readonly bool _keyboard;
            private byte[][] _crash = Array.Empty<byte[]>();

            public Session(bool keyboard) => _keyboard = keyboard;

            public override bool Feature => true;

            /// <summary>The release, once control may have been taken.</summary>
            public override byte[][] CrashFrames => _crash;

            public override HidLightingPaint Paint(IHidReportChannel io, Action<int> wait,
                IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
            {
                if (_crash.Length == 0)
                {
                    // Marked first: a write that reports a failure may still
                    // have landed.
                    _crash = ControlFrames(0x00);
                    foreach (var frame in ControlFrames(0x01))
                        if (!io.SetFeature(frame)) return HidLightingPaint.Failed;
                }
                if (_keyboard)
                {
                    foreach (var frame in KeyboardFrames(lights, colors))
                        if (!io.SetFeature(frame)) return HidLightingPaint.Failed;
                    return HidLightingPaint.Sent;
                }
                return io.SetFeature(MouseFrame(lights, colors)) ? HidLightingPaint.Sent : HidLightingPaint.Failed;
            }

            public override bool HandBack(IHidReportChannel io, Action<int> wait)
            {
                if (_crash.Length == 0) return true;
                foreach (var frame in _crash)
                    if (!io.SetFeature(frame)) return false;
                _crash = Array.Empty<byte[]>();
                return true;
            }
        }
    }
}
