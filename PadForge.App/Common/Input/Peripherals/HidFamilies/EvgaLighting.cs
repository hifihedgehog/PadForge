    /// <summary>
    /// EVGA's Z15 and Z20 keyboards, its X20 mouse (wired, and on its USB
    /// receiver) and its X12 mouse, lit as OpenRGB's EVGAUSBController
    /// lights them (#557). The collections are OpenRGB's registrations
    /// (EVGAKeyboardControllerDetect.cpp:45-48, EVGAMouseControllerDetect.cpp:53-54,
    /// EVGAX12ControllerDetect.cpp:40), each with feature reports of the
    /// length its frames take.
    ///
    /// <para>Keyboards. The lights are OpenRGB's: 108 keys, and on the Z20
    /// nine lights down each side and six macro keys
    /// (RGBController_EVGAKeyboard.cpp:17-185 and 398-467, generated by
    /// tools/gen_laptop_misc_led_tables.py). A picture goes out as OpenRGB's
    /// Direct mode sends it, one 792-byte feature report with each light's
    /// brightness and color at the slot its packet map gives it and a
    /// checksum (SetLedsDirect, EVGAKeyboardController.cpp:103-125). The
    /// mode saves nothing ("@save :x:"). The hand-back is the report OpenRGB
    /// sends when it leaves Direct for one of the keyboard's own modes,
    /// "Initialise Hardware Modes" (SetHWModes, lines 198-206, sent from
    /// RGBController_EVGAKeyboard.cpp:501-504). OpenRGB then sends the mode it
    /// is going to (SetMode, EVGAKeyboardController.cpp:134-140). PadForge has
    /// none to send: OpenRGB's calls to GetMode and GetStatus are commented
    /// out (RGBController_EVGAKeyboard.cpp:232-387), GetMode needs packets its
    /// author could not explain (NFIPacket, EVGAKeyboardController.cpp:392-396),
    /// and SignalRGB's plugin ends on a last color frame
    /// (Z-20_Keyboard.js:79-81). That the keyboard resumes its stored effect
    /// from this report alone is taken from its name and has not been seen on
    /// a device. OpenRGB also sets the
    /// keyboard's sleep timer whenever it opens one (SetSleepTime,
    /// EVGAKeyboardController.cpp:67 and 405-426), a setting of the user's
    /// that has nothing to do with the colors, which PadForge leaves
    /// alone.</para>
    ///
    /// <para>The X20 mouse. Three lights, front, wheel and logo, each with a
    /// mode of its own (RGBController_EVGAMouse.cpp:146-189). A session reads
    /// each light's mode, brightness, speed and colors first
    /// (RefreshDeviceState, EVGAMouseController.cpp:237-276). Its first
    /// picture puts each light in the Static mode (SetMode, lines 112-136),
    /// and then each picture sets each light's color, every write followed
    /// by a read of the answer, which the mouse may have to be asked for
    /// again while it is not ready, up to 100 times (SetLed,
    /// lines 176-228, ReadPacketOrWait, lines 300-312). OpenRGB marks the
    /// Static mode as saved on the mouse (MODE_FLAG_AUTOMATIC_SAVE,
    /// RGBController_EVGAMouse.cpp:40), so a changed picture holds for
    /// <see cref="HoldMs"/> and pictures are <see cref="RepaintMs"/> apart.
    /// The hand-back writes back what the session read: each light's mode,
    /// then its brightness, speed and colors, as OpenRGB writes a mode
    /// (DeviceUpdateMode, RGBController_EVGAMouse.cpp:214-240). Each color
    /// frame carries its own light's mode, where OpenRGB puts the logo's in
    /// all three, its own limit by its comment: "Unleash RGB supports
    /// individual modes on the LEDs, but OpenRGB does not"
    /// (EVGAMouseController.cpp:195-199). The speed is read at the offset it
    /// is written to (EVGA_PERIPHERAL_SPEED_BYTE, EVGAMouseController.h:58),
    /// which OpenRGB does not read.</para>
    ///
    /// <para>The X12 mouse. Three lights, side, wheel and logo, in firmware
    /// slots 0, 2 and 3 of four (EVGAX12Controller.h:38-44,
    /// EVGAX12Controller.cpp:29-34). A session reads the slots' modes and
    /// static colors first (GetLightingState, lines 71-102). Its first
    /// picture writes the colors and turns the static mode on
    /// (SetStaticAndActivate, lines 140-157), later ones the colors alone,
    /// each write checked by reading it back, up to three tries
    /// (SetStaticReport, lines 159-218). The X12's changes do not last past
    /// a reconnect, OpenRGB notes (RGBController_EVGAX12.cpp:22-23). The
    /// hand-back writes back the colors and modes the session read.</para>
    ///
    /// <para>No source names a process of EVGA's Unleash RGB, so no program
    /// is listed.</para>
    /// </summary>
    internal sealed partial class EvgaLighting : IHidLightingFamily
    {
        public static readonly EvgaLighting Instance = new();

        internal const string OpenRgbFamily = "EVGAUSBController";

        internal const string KeyboardDetector = "DetectEVGAKeyboardControllers";
