using System;
using System.Collections.Generic;
using PadForge.Common.Input.Peripherals.HidFamilies;

namespace PadForge.Common.Input.Peripherals
{
    /// <summary>
    /// The Alienware AW410K and AW510K keyboards (04F2:1968 and 04F2:1830)
    /// that OpenRGB's AlienwareKeyboardController lights key by key (#557).
    /// The collections are OpenRGB's registrations
    /// (AlienwareAW410KControllerDetect.cpp:43, AlienwareAW510KControllerDetect.cpp:43),
    /// interface 2, usage page 0xFF00, with output and feature reports of
    /// <see cref="ReportSize"/> bytes.
    ///
    /// <para>The lights are OpenRGB's tables, each key at its cell of the
    /// grid and each light's address its index in the direct frames
    /// (led_names and matrix_map of RGBController_AlienwareAW410K.cpp and
    /// RGBController_AlienwareAW510K.cpp, generated by
    /// tools/gen_laptop_misc_led_tables.py). The AW510K's "Logo" light is a
    /// logo light.</para>
    ///
    /// <para>A picture goes out as OpenRGB's Direct mode sends it
    /// (DeviceUpdateLEDs): an initialize output report, the feature report
    /// 05 01 51 00, a commit output report, then the feature report that
    /// announces the key count and the keys four to an output report
    /// (SendInitialize, SendfeatureReport, SendCommit and SendDirectOn in
    /// AlienwareAW410KController.cpp:54-304), with OpenRGB's waits of 2 ms,
    /// 10 ms and 20 ms after them. The AW410K's controller sends every key
    /// (RGBController_AlienwareAW410K.cpp:323-352). The AW510K's sends the
    /// keys whose color changed since its last picture
    /// (RGBController_AlienwareAW510K.cpp:322-373), and here its first
    /// picture of a session sends every key, since what the keyboard showed
    /// before is not known, where OpenRGB takes it to be black and leaves
    /// the black keys out. OpenRGB marks the mode as one that saves nothing
    /// ("@save :x:").</para>
    ///
    /// <para>Hand-back. Nothing goes out: no reference reads the keyboard's
    /// mode or returns it to its own effect. The keyboard shows PadForge's
    /// last picture until Alienware Command Center sets another or it is
    /// plugged in again.</para>
    ///
    /// <para>Alienware Command Center lights these keyboards, and while it
    /// runs the keyboard is left to it
    /// (<see cref="VendorPrograms.AlienwareCommandCenter"/>).</para>
    /// </summary>
    internal sealed partial class AlienwareKeyboardLighting : IHidLightingFamily
    {
        public static readonly AlienwareKeyboardLighting Instance = new();

        internal const string OpenRgbFamily = "AlienwareKeyboardController";

        /// <summary>Every report's length with the report ID 0
        /// (AlienwareAW410KController.cpp:56 and 94).</summary>
        internal const int ReportSize = 65;

        internal const ushort Aw410kPid = 0x1968;
        internal const ushort Aw510kPid = 0x1830;

        /// <summary>The shortest time between two pictures, PadForge's bound
        /// for a mode that saves nothing
        /// (<see cref="AsusTufLaptopLighting.RepaintMs"/>).</summary>
        internal const int RepaintMs = AsusTufLaptopLighting.RepaintMs;

        public string Name => "Alienware Keyboard";

        private static readonly Lazy<HidLightingModel> s_aw410k = new(() => Model("Alienware AW410K", Aw410kPid));
        private static readonly Lazy<HidLightingModel> s_aw510k = new(() => Model("Alienware AW510K", Aw510kPid));

        public HidLightingModel Match(HidCollectionInfo collection)
        {
            if (collection == null || collection.FeatureReportLength < ReportSize
                || collection.OutputReportLength < ReportSize)
                return null;
            if (OpenRgbRegistrations.Match(OpenRgbFamily, collection).Count == 0) return null;
            return collection.ProductId switch
            {
                Aw410kPid => s_aw410k.Value,
                Aw510kPid => s_aw510k.Value,
                _ => null,
            };
        }

        private static HidLightingModel Model(string name, ushort productId)
        {
            bool aw510k = productId == Aw510kPid;
            return new HidLightingModel
            {
                Family = Instance,
                Name = name,
                Map = new LightMap(aw510k ? Lights(Aw510kLeds, Aw510kGrid, Aw510kCols) : Lights(Aw410kLeds, Aw410kGrid, Aw410kCols),
                    "OpenRGB AlienwareKeyboardController")
                {
                    Product = $"alienware:04F2:{productId:X4}",
                },
                Programs = new[] { VendorPrograms.AlienwareCommandCenter },
                RepaintMs = RepaintMs,
                Begin = (_, _) => new Session(aw510k),
            };
        }

        /// <summary>The lights of a table: each key's usage from its name,
        /// its address its index in the direct frames, its place the grid
        /// cell that holds it. A light no key name covers is an Other light
        /// with its label, the "Logo" light a logo light.</summary>
        internal static IReadOnlyList<LightInfo> Lights((string Name, byte Value)[] leds, uint[] grid, int cols)
        {
            var lights = new List<LightInfo>(leds.Length);
            for (int i = 0; i < leds.Length; i++)
            {
                var (name, value) = leds[i];
                LightInfo light;
                if (OpenRgbKeys.TryGet(name, out ushort usage, out var label, out int number) && usage != 0)
                    light = new LightInfo(value, LightKind.Key, usage, LightKeySource.Generated);
                else if (name == "Logo")
                    light = new LightInfo(value, LightKind.Logo, 0, LightKeySource.None);
                else
                    light = new LightInfo(value, LightKind.Other, 0, LightKeySource.None) { Label = label, LabelNumber = number };
                for (int cell = 0; cell < grid.Length; cell++)
                    if (grid[cell] == (uint)i)
                    {
                        light = light with { X = cell % cols, Y = cell / cols, Width = 1, Height = 1, HasPosition = true };
                        break;
                    }
                lights.Add(light);
            }
            return lights;
        }

        // ─────────────────────────────────────────────
        //  The reports
        // ─────────────────────────────────────────────

        /// <summary>SendInitialize's output report
        /// (AlienwareAW410KController.cpp:149-182).</summary>
        internal static byte[] Initialize()
        {
            var report = new byte[ReportSize];
            report[1] = 0x0E;
            report[2] = 0x01;
            report[4] = 0x01;
            report[5] = 0xAD;
            report[6] = 0x80;
            report[7] = 0x10;
            report[8] = 0xA5;
            report[0x0A] = 0x0A;
            report[0x12] = 0x01;
            return report;
        }

        /// <summary>SendfeatureReport's feature report of four bytes after
        /// the report ID (lines 86-119).</summary>
        internal static byte[] FeatureFrame(byte a, byte b, byte c, byte d)
        {
            var report = new byte[ReportSize];
            report[1] = a;
            report[2] = b;
            report[3] = c;
            report[4] = d;
            return report;
        }

        /// <summary>SendCommit's output report (lines 54-84).</summary>
        internal static byte[] Commit()
        {
            var report = new byte[ReportSize];
            report[1] = 0x05;
            report[2] = 0x01;
            report[0x0A] = 0x10;
            report[0x0B] = 0x0A;
            report[0x0C] = 0x01;
            report[0x0D] = 0x02;
            report[0x0E] = 0x01;
            return report;
        }

        /// <summary>SendDirectOn's output reports (lines 225-304): four keys
        /// to a report, numbered from 1 in byte 4, each key's slot of 15
        /// bytes its index, 81 00 A5, 0A, its color and 01. The keys are
        /// padded with zeros to a multiple of four as the padding loop
        /// leaves them, a loop that stops once the count divides by four
        /// (lines 236-245).</summary>
        internal static List<byte[]> DirectFrames(IReadOnlyList<(byte Index, int Rgb)> keys)
        {
            var padded = new List<(byte Index, int Rgb)>(keys);
            for (int i = 0; i < padded.Count % 4; i++) padded.Add((0, 0));
            var reports = new List<byte[]>();
            var report = new byte[ReportSize];
            int number = 0;
            for (int k = 0; k < padded.Count; k += 4)
            {
                report[1] = 0x0E;
                report[2] = 0x01;
                report[3] = 0x00;
                report[4] = (byte)++number;
                for (int slot = 0; slot < 4; slot++)
                {
                    int at = 5 + slot * 15;
                    var (index, rgb) = padded[k + slot];
                    report[at] = index;
                    report[at + 1] = 0x81;
                    report[at + 2] = 0x00;
                    report[at + 3] = 0xA5;
                    report[at + 5] = 0x0A;
                    report[at + 6] = (byte)(rgb >> 16);
                    report[at + 7] = (byte)(rgb >> 8);
                    report[at + 8] = (byte)rgb;
                    report[at + 13] = 0x01;
                }
                reports.Add((byte[])report.Clone());
            }
            return reports;
        }

        internal sealed class Session : HidLightingSession
        {
            private readonly bool _changedOnly;
            private Dictionary<byte, int> _shown;

            public Session(bool changedOnly) => _changedOnly = changedOnly;

            public override bool Feature => false;

            public override byte[][] CrashFrames => Array.Empty<byte[]>();

            /// <summary>DeviceUpdateLEDs: the keys to send, then initialize,
            /// 05 01 51 00, commit, and when there are keys, the count and
            /// the keys.</summary>
            public override HidLightingPaint Paint(IHidReportChannel io, Action<int> wait,
                IReadOnlyList<LightInfo> lights, IReadOnlyList<int> colors)
            {
                int count = Math.Min(lights?.Count ?? 0, colors?.Count ?? 0);
                var keys = new List<(byte Index, int Rgb)>(count);
                var shown = new Dictionary<byte, int>(count);
                for (int n = 0; n < count; n++)
                {
                    byte index = (byte)lights[n].Address;
                    int rgb = colors[n] & 0xFFFFFF;
                    shown[index] = rgb;
                    if (_changedOnly && _shown != null && _shown.TryGetValue(index, out int was) && was == rgb) continue;
                    keys.Add((index, rgb));
                }
                if (!io.WriteOutput(Initialize())) return HidLightingPaint.Failed;
                wait(2);
                if (!io.SetFeature(FeatureFrame(0x05, 0x01, 0x51, 0x00))) return HidLightingPaint.Failed;
                wait(10);
                if (!io.WriteOutput(Commit())) return HidLightingPaint.Failed;
                wait(20);
                if (keys.Count > 0)
                {
                    if (!io.SetFeature(FeatureFrame(0x0E, (byte)keys.Count, 0x00, 0x01))) return HidLightingPaint.Failed;
                    wait(10);
                    foreach (var report in DirectFrames(keys))
                        if (!io.WriteOutput(report)) return HidLightingPaint.Failed;
                }
                _shown = shown;
                return HidLightingPaint.Sent;
            }

            public override bool HandBack(IHidReportChannel io, Action<int> wait) => true;
        }
    }
}
